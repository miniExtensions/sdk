import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import vm from 'node:vm';
import {
    compilePostgresPresentationRuntime,
    postgresPresentationRuntimeOutputHashes,
    rewritePostgresPresentationRuntime,
} from './postgres-presentation-runtime-artifacts.mjs';

const portable = () =>
    readFileSync(
        new URL(
            '../src/runtime/contracts/postgresTextPresentation.generated.ts',
            import.meta.url
        ),
        'utf8'
    );

test('portable presentation emission preserves canonical behavior in ESM and CommonJS', async () => {
    const source = portable();
    const generated = await rewritePostgresPresentationRuntime(source, {});
    assert.equal(
        await rewritePostgresPresentationRuntime(source, {}),
        generated
    );
    const output = compilePostgresPresentationRuntime(generated);
    const esm = await import(
        'data:text/javascript;base64,' +
            Buffer.from(output.esm).toString('base64')
    );
    const commonjs = { exports: {} };
    vm.runInNewContext(output.cjs, commonjs);
    for (const runtime of [esm, commonjs.exports]) {
        const descriptor = runtime.postgresTextColumnPresentationDefinition;
        assert.equal(descriptor.sourceType, 'postgres');
        assert.equal(descriptor.columnKind, 'text');
        for (const state of [
            {},
            { displayAs: undefined },
            { displayAs: 'text' },
        ]) {
            const value = runtime.resolvePostgresTextColumnPresentation(
                Object.freeze(state)
            );
            assert.equal(value, descriptor.choices[0].presentation);
            assert.equal(value.nativeValueInput, 'applicable');
            assert.equal(value.storedValue, 'text');
        }
        const state = Object.freeze({
            displayAs: 'attachments-public-urls',
            readOnly: false,
        });
        const value = runtime.resolvePostgresTextColumnPresentation(state);
        assert.equal(value, descriptor.choices[1].presentation);
        assert.equal(value.nativeValueInput, 'read-only');
        assert.equal(value.fileOpening, 'existing-public-http-urls');
        assert.equal(value.attachmentMutation, 'excluded');
        assert.equal(value.generatedAttachmentOutput, 'excluded');
        assert.equal(state.readOnly, false);
        for (const displayAs of [null, '', false, 0, [], {}, 'private-mode'])
            assert.throws(
                () =>
                    runtime.resolvePostgresTextColumnPresentation({
                        displayAs,
                    }),
                (error) =>
                    error instanceof
                        runtime.PostgresTextColumnPresentationError &&
                    error.reason === 'INVALID_PRESENTATION' &&
                    !error.message.includes('private-mode')
            );
    }
    const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
    const hashes = postgresPresentationRuntimeOutputHashes(generated);
    assert.equal(hashes.generatedSha256, hash(generated));
    assert.deepEqual(hashes.moduleSha256, {
        esm: hash(output.esm),
        cjs: hash(output.cjs),
    });
    assert.equal(hashes.declarationsSha256, hash(output.declaration));
    assert(!output.declaration.includes('zod'));
    assert(!output.declaration.includes('import('));
});

test('policy relocation removes private canonical banners before JS and declaration emission', async () => {
    const path = 'types/scripts/postgres-configs/generate.ts';
    const generated = await rewritePostgresPresentationRuntime(
        `// Generated by ${path}; private canonical banner\n` + portable(),
        {}
    );
    const output = compilePostgresPresentationRuntime(generated);
    for (const text of [
        generated,
        output.esm,
        output.cjs,
        output.declaration,
    ]) {
        assert(!text.includes(path));
        assert(!text.includes('private canonical banner'));
    }
});

test('policy relocation refuses module dependencies, expanded exports and callback metadata', async () => {
    const source = portable();
    for (const invalid of [
        "import type { Private } from './private';\n" + source,
        source + "\nexport { privateHelper } from './private';\n",
        source.replace(
            'const value = Object.is',
            "const dependency = require('./private');\n const value = Object.is"
        ),
        source + '\nexport const unexpected = 1;\n',
        source.replace(
            "sourceType: 'postgres'",
            "sourceType: () => 'postgres'"
        ),
        '/// <reference path="./private.d.ts" />\n' + source,
    ])
        await assert.rejects(
            rewritePostgresPresentationRuntime(invalid, {}),
            /portable|export|statement|callback-free|references/
        );
    await assert.rejects(
        rewritePostgresPresentationRuntime('export const = ;', {}),
        /invalid syntax/
    );
});
