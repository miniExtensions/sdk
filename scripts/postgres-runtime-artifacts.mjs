import { createHash } from 'node:crypto';
import ts from 'typescript';
import prettier from 'prettier';

export const postgresAttachmentRuntimeModule =
    'postgresAttachmentDisplay.generated';
export const postgresAttachmentRuntimeSource =
    'types/postgres/attachmentDisplay.ts';
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');

/** Relocate the authored module; do not maintain a second implementation. */
export async function rewritePostgresAttachmentRuntime(source, formatOptions) {
    const file = ts.createSourceFile(
        postgresAttachmentRuntimeSource,
        source,
        ts.ScriptTarget.ES2022,
        true,
        ts.ScriptKind.TS
    );
    if (file.parseDiagnostics.length)
        throw new Error(
            'Canonical PostgreSQL display runtime has invalid syntax.'
        );
    const imports = file.statements.filter(ts.isImportDeclaration);
    const original = imports[0];
    const clause = original?.importClause;
    const bindings = clause?.namedBindings;
    if (
        imports.length !== 1 ||
        !clause?.isTypeOnly ||
        clause.name != null ||
        !bindings ||
        !ts.isNamedImports(bindings) ||
        bindings.elements.length !== 1 ||
        bindings.elements[0].name.text !== 'PostgresValue' ||
        bindings.elements[0].propertyName != null ||
        !ts.isStringLiteral(original.moduleSpecifier) ||
        original.moduleSpecifier.text !== './types'
    )
        throw new Error(
            'Unexpected canonical PostgreSQL display runtime imports.'
        );
    const inspect = (node) => {
        if (
            ts.isImportEqualsDeclaration(node) ||
            ts.isImportTypeNode(node) ||
            (ts.isExportDeclaration(node) && node.moduleSpecifier != null) ||
            (ts.isCallExpression(node) &&
                (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
                    (ts.isIdentifier(node.expression) &&
                        node.expression.text === 'require')))
        )
            throw new Error('PostgreSQL display runtime must remain portable.');
        ts.forEachChild(node, inspect);
    };
    inspect(file);
    const relocated = ts.factory.updateImportDeclaration(
        original,
        original.modifiers,
        ts.factory.createImportClause(
            true,
            undefined,
            ts.factory.createNamedImports([
                ts.factory.createImportSpecifier(
                    false,
                    ts.factory.createIdentifier('CanonicalPostgresValue'),
                    ts.factory.createIdentifier('PostgresValue')
                ),
            ])
        ),
        ts.factory.createStringLiteral('./postgres.generated.js'),
        original.attributes
    );
    const portable = ts.factory.updateSourceFile(
        file,
        file.statements.map((statement) =>
            statement === original ? relocated : statement
        )
    );
    // Source paths and revisions belong only in the private manifest. In
    // particular, real imports can retain leading comments in declaration emit.
    return prettier.format(
        '// Generated by scripts/generate-runtime-contracts.mjs; do not edit.\n' +
            ts
                .createPrinter({ newLine: ts.NewLineKind.LineFeed })
                .printFile(portable),
        { ...formatOptions, parser: 'typescript' }
    );
}

/** Independent expected compiler bytes, recorded before the package build. */
export function compilePostgresRuntime(source) {
    const outputs = {};
    for (const [format, module] of [
        ['esm', ts.ModuleKind.ESNext],
        ['cjs', ts.ModuleKind.CommonJS],
    ]) {
        const result = ts.transpileModule(source, {
            fileName: `${postgresAttachmentRuntimeModule}.ts`,
            reportDiagnostics: true,
            compilerOptions: {
                target: ts.ScriptTarget.ES2022,
                module,
                esModuleInterop: true,
                newLine: ts.NewLineKind.LineFeed,
            },
        });
        if (result.diagnostics?.length)
            throw new Error(
                'Could not compile portable PostgreSQL display runtime.'
            );
        outputs[format] = result.outputText;
    }
    const declaration = ts.transpileDeclaration(source, {
        fileName: `${postgresAttachmentRuntimeModule}.ts`,
        reportDiagnostics: true,
        compilerOptions: {
            target: ts.ScriptTarget.ES2022,
            module: ts.ModuleKind.ESNext,
            newLine: ts.NewLineKind.LineFeed,
        },
    });
    if (declaration.diagnostics?.length)
        throw new Error(
            'Could not declare portable PostgreSQL display runtime.'
        );
    return { ...outputs, declaration: declaration.outputText };
}

export function postgresRuntimeOutputHashes(source) {
    const output = compilePostgresRuntime(source);
    return {
        generatedSha256: hash(source),
        moduleSha256: { esm: hash(output.esm), cjs: hash(output.cjs) },
        declarationsSha256: hash(output.declaration),
    };
}
